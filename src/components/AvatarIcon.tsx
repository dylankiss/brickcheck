/** The head without the lines inside it: the first outline of the path. */
const silhouette = (outline: string) => outline.slice(0, outline.indexOf("m"));

/**
 * An avatar's head: black line art on a light face, which reads the same on
 * every background colour. A stroke on top of the outlines keeps the lines
 * from fading at small sizes.
 */
export function AvatarIcon({
  icon,
  face,
  className = "",
}: {
  icon: AvatarIconId;
  /** The colour of the face, a light one. */
  face: string;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 512 512"
      fill="#000"
      stroke="#000"
      strokeWidth={70}
      strokeLinejoin="round"
      aria-hidden
      className={className}
    >
      <g transform="translate(0 512) scale(0.1 -0.1)">
        <path d={silhouette(OUTLINES[icon])} fill={face} stroke="none" />
        <path d={OUTLINES[icon]} />
        <g transform={icon === "head" ? "translate(0 240)" : undefined}>
          <path d={EYE_LEFT} />
          <path d={EYE_RIGHT} />
          <path d={SMILE} />
        </g>
      </g>
    </svg>
  );
}
